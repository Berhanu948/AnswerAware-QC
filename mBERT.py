# 10. Mean training and validation curves
# ============================================================
# Extract epoch-level logs from each run.
# Average only epochs available in all runs.
epoch_logs = []
for history in all_histories:
    epoch_logs.append([
        entry for entry in history
        if "epoch" in entry
        and ("loss" in entry or "eval_loss" in entry)    ])
min_epochs = min(len(logs) for logs in epoch_logs)
train_loss = []
val_loss = []
train_acc = []
val_acc = []
for epoch_idx in range(min_epochs):
    train_loss.append(np.mean([
        next(
            (entry["loss"] for entry in logs
             if "loss" in entry and "eval_loss" not in entry),
            np.nan
        )
        for logs in epoch_logs
    ]))

    val_loss.append(np.mean([
        next(
            (entry["eval_loss"] for entry in logs
             if "eval_loss" in entry),
            np.nan
        )
        for logs in epoch_logs
    ]))

    train_acc.append(np.mean([
        next(
            (entry.get("train_accuracy", np.nan)
             for entry in logs
             if "train_accuracy" in entry),
            np.nan
        )
        for logs in epoch_logs
    ]))
    val_acc.append(np.mean([
        next(
            (entry["eval_accuracy"] for entry in logs
             if "eval_accuracy" in entry),
            np.nan        )
        for logs in epoch_logs    ]))
epochs_range = range(1, min_epochs + 1)
plt.figure(figsize=(8, 5))
plt.plot(epochs_range, train_loss, label="Mean training loss")
